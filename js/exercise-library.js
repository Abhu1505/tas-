// ============================================================
// Dropdown population helpers
// ============================================================

window.populateCategoryDropdown = function () {
  const sel = document.getElementById('libCategorySelect');
  if (!sel) return;
  sel.innerHTML = '<option value="">— Select Category —</option>';
  Object.keys(window.EXERCISE_LIBRARY).forEach(cat => {
    const opt = document.createElement('option');
    opt.value = cat;
    opt.textContent = cat;
    sel.appendChild(opt);
  });
};

window.populateSubCategoryDropdown = function (category) {
  const sel = document.getElementById('libSubCategorySelect');
  const exSel = document.getElementById('libExerciseSelect');
  if (!sel || !exSel) return;
  sel.innerHTML = '<option value="">— Select Sub-category —</option>';
  exSel.innerHTML = '<option value="">— Select Exercise —</option>';
  if (!category || !window.EXERCISE_LIBRARY[category]) return;
  Object.keys(window.EXERCISE_LIBRARY[category]).forEach(sub => {
    const opt = document.createElement('option');
    opt.value = sub;
    opt.textContent = sub;
    sel.appendChild(opt);
  });
  // Auto-select if only one sub-category (e.g., "—")
  const subs = Object.keys(window.EXERCISE_LIBRARY[category]);
  if (subs.length === 1) {
    sel.value = subs[0];
    populateExerciseDropdown(category, subs[0]);
  }
};

window.populateExerciseDropdown = function (category, subCategory) {
  const exSel = document.getElementById('libExerciseSelect');
  if (!exSel) return;
  exSel.innerHTML = '<option value="">— Select Exercise —</option>';
  if (!category || !subCategory) return;
  const list = (window.EXERCISE_LIBRARY[category] || {})[subCategory] || [];
  list.forEach(name => {
    const opt = document.createElement('option');
    opt.value = name;
    opt.textContent = name;
    exSel.appendChild(opt);
  });
};

// ============================================================
// Wire up: on category change → sub-category, on sub → exercises
// ============================================================
window.initLibraryDropdowns = function () {
  const catSel = document.getElementById('libCategorySelect');
  const subSel = document.getElementById('libSubCategorySelect');
  const exSel  = document.getElementById('libExerciseSelect');
  const addBtn = document.getElementById('libAddExerciseBtn');
  if (!catSel || !subSel || !exSel || !addBtn) return;

  populateCategoryDropdown();

  catSel.addEventListener('change', () => {
    populateSubCategoryDropdown(catSel.value);
  });

  subSel.addEventListener('change', () => {
    populateExerciseDropdown(catSel.value, subSel.value);
  });

  addBtn.addEventListener('click', async () => {
    const cat = catSel.value;
    const sub = subSel.value;
    const exName = exSel.value;
    if (!cat || !sub || !exName) {
      showStatus(document.getElementById('dayLogStatus'), '⚠️ Please select category, sub-category, and exercise.', 'error');
      return;
    }
    // Match against existing library (if it exists) so we link exercise_id when possible
    const matched = APP_STATE.exercises.find(e => e.name.toLowerCase() === exName.toLowerCase());
    await addExerciseToDay({ name: exName, exercise_id: matched ? matched.id : null });
    // Reset dropdowns
    catSel.value = '';
    populateSubCategoryDropdown('');
    openDayLogModal(APP_STATE.selectedDay);
  });
};